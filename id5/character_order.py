# 名字 -> 名次。表外的名字**不给默认值**，由 order_key 兜底 —— 见那里的说明。
_RANK = {name: i for i, name in enumerate(ORDER)}

# 表里有重名的话 _RANK 会静默吞掉一个（后者覆盖前者），而表现是"某个角色的位置
# 莫名跑到别人那儿去了"，很难往这张表上想。导入时就拦住。
assert len(_RANK) == len(ORDER), "character_order.ORDER 里有重名"

# 表外角色的名次。取一个比表内任何名次都大的值 —— 于是它们**排在最新的一端**。
# 方向不能反：新增角色时我们先拿到图片、后更新这张表（甚至可能忘了更新），
# 期间它必须出现在"最新的那批"里。排到最老的一端等于把它埋进 88 个头像中间，
# 而操作者的需求恰恰是**把新角色排除出随机范围**，找不到就等于功能失效。
_UNKNOWN_RANK = len(ORDER)


def order_key(name):
    """排序键：越小 = 实装越早。表外的名字排在**最后**（= 最新）。

    同名的两个表外角色（不存在，但别让排序在它们之间变得不确定）按名字兜底。
    """
    return (_RANK.get(name, _UNKNOWN_RANK), name)


def ordered(names):
    """把一批角色名按实装顺序（早 → 晚）排好，返回新列表。

    表外的名字排在最后，而不是丢掉 —— 调用方传进来的通常是**磁盘上真实存在
    的所有角色**，丢一个就等于那个角色永远没法被规则禁用。
    """
    return sorted(names, key=order_key)


def newest_first(names):
    """实装顺序**倒序**（新 → 旧）。规则禁用窗要的就是这个顺序。"""
    return sorted(names, key=order_key, reverse=True)
